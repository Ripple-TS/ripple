// Generates `src/dom-setters.js`: the settable properties of every HTML element
// interface, read from TypeScript's `lib.dom.d.ts`. Run from the package:
//   node scripts/generate-dom-setters.js
// The client transform consults it so a `data-` attribute or any other name
// that is not a property of its element is written with `setAttribute` alone,
// and a property with a non-string value is assigned, without the runtime
// discovering the element's setters with descriptor walks (`set_attribute`).
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const ts = require('typescript');
const lib = require.resolve('typescript/lib/lib.dom.d.ts');
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/dom-setters.js');

export function generate() {
	const source = ts.createSourceFile(lib, readFileSync(lib, 'utf8'), ts.ScriptTarget.Latest);
	/** @type {Map<string, { extends: string[], writable: string[] }>} */
	const interfaces = new Map();
	/** @type {Map<string, string>} */
	const tags = new Map();
	for (const statement of source.statements) {
		if (!ts.isInterfaceDeclaration(statement)) continue;
		const name = statement.name.text;
		if (name === 'HTMLElementTagNameMap') {
			for (const member of statement.members) {
				if (ts.isPropertySignature(member) && member.type && ts.isTypeReferenceNode(member.type)) {
					tags.set(
						ts.isStringLiteral(member.name) ? member.name.text : member.name.getText(source),
						member.type.typeName.getText(source),
					);
				}
			}
			continue;
		}
		const entry = interfaces.get(name) ?? { extends: [], writable: [] };
		for (const clause of statement.heritageClauses ?? []) {
			for (const type of clause.types) entry.extends.push(type.expression.getText(source));
		}
		for (const member of statement.members) {
			if (
				ts.isPropertySignature(member) &&
				!member.modifiers?.some((m) => m.kind === ts.SyntaxKind.ReadonlyKeyword) &&
				(ts.isIdentifier(member.name) || ts.isStringLiteral(member.name))
			) {
				entry.writable.push(member.name.text);
			}
		}
		interfaces.set(name, entry);
	}

	// The runtime walk stops at `Element.prototype`, so the setters of Element
	// and its mixins (id, className, innerHTML, scroll offsets, ARIA) are not
	// properties to it either.
	/** @param {string} name @param {Set<string>} into */
	const collect = (name, into) => {
		if (name === 'Element') return;
		const entry = interfaces.get(name);
		if (!entry) return;
		for (const property of entry.writable) into.add(property);
		for (const parent of entry.extends) collect(parent, into);
	};
	const shared = new Set();
	collect('HTMLElement', shared);
	/** @type {Record<string, string[]>} */
	const specific = {};
	for (const [tag, interface_name] of [...tags].sort()) {
		const own = new Set();
		collect(interface_name, own);
		const extra = [...own].filter((property) => !shared.has(property)).sort();
		if (extra.length > 0) specific[tag] = extra;
	}
	const list = (values) => JSON.stringify(values).replaceAll('"', "'").replaceAll(',', ', ');
	return `// Generated by scripts/generate-dom-setters.js from TypeScript ${ts.version}'s
// lib.dom.d.ts. Do not edit.

/**
 * Settable properties of \`HTMLElement\` and its mixins, which every HTML
 * element has (\`Element\`'s own are left out, as the runtime's setter walk
 * leaves them out).
 */
export const HTML_ELEMENT_SETTERS = new Set(${list([...shared].sort())});

/**
 * The settable properties an HTML element interface adds to
 * {@link HTML_ELEMENT_SETTERS}, by tag name; a tag not listed adds none.
 * @type {Record<string, readonly string[]>}
 */
export const HTML_TAG_SETTERS = {
${Object.entries(specific)
	.map(([tag, extra]) => `\t${/^[a-z][a-z0-9]*$/.test(tag) ? tag : `'${tag}'`}: ${list(extra)},`)
	.join('\n')}
};

/** Every tag of \`HTMLElementTagNameMap\`. */
export const HTML_TAGS = new Set(${list([...tags.keys()].sort())});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(out, generate());
	console.log(`wrote ${path.relative(process.cwd(), out)}`);
}
